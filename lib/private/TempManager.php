namespace OC;

use bantu\IniGetWrapper\IniGetWrapper;
use OCP\Files;
use OCP\IConfig;
use OCP\ITempManager;
use OCP\Security\ISecureRandom;
use OCP\Server;
use Psr\Log\LoggerInterface;

class TempManager implements ITempManager {
	/** @var string[] Current temporary files and folders, used for cleanup */
	protected array $current = [];
	/** @var ?string i.e. /tmp on linux systems */
	protected ?string $tmpBaseDir = null;

	/** Prefix */
	public const TMP_PREFIX = 'oc_tmp_';
	public const TMP_STALE = 60 * 60;

	public function __construct(
		protected LoggerInterface $log,
		protected IConfig $config,
		protected IniGetWrapper $iniGetWrapper,
	) {
		$this->tmpBaseDir = $this->getTempBaseDir();
	}
	
	/**
	 * Generate a unique path below the configured temporary directory.
	 *
	 * The returned path is not created. Any path separators in the suffix are
	 * removed so that the result remains directly below the temporary base
	 * directory.
	 *
	 * @param string $postFix Optional filename suffix, such as `tar.gz`
	 * @return string Local filesystem path
	 */
	private function generateTemporaryPath(string $postFix): string {
		$secureRandom = Server::get(ISecureRandom::class);
		$absolutePath = $this->tmpBaseDir . '/' . self::TMP_PREFIX . $secureRandom->generate(32, ISecureRandom::CHAR_ALPHANUMERIC);

		if ($postFix === '') {
			return $absolutePath;
		}

		$postFix = '.' . ltrim($postFix, '.');
		$postFix = str_replace(['\\', '/'], '', $postFix);

		return $absolutePath . $postFix;
	}

	#[\Override]
	public function getTemporaryFile(string $postFix = ''): string|false {
		$path = $this->generateTemporaryPath($postFix);

		$old_umask = umask(0077);
		$fp = @fopen($path, 'x');
		umask($old_umask);

		if ($fp === false) {
			$this->log->warning(
				'Can not create a temporary file in directory {dir}. Check it exists and has correct permissions',
				[
					'dir' => $this->tmpBaseDir,
					'error' => error_get_last(),
				]
			);
			return false;
		}

		fclose($fp);
		$this->current[] = $path;

		return $path;
	}

	#[\Override]
	public function getTemporaryFolder(string $postFix = ''): string|false {
		$path = $this->generateTemporaryPath($postFix) . '/';

		if (@mkdir($path, 0700) === false) {
			$this->log->warning(
				'Can not create a temporary folder in directory {dir}. Check it exists and has correct permissions',
				[
					'dir' => $this->tmpBaseDir,
					'error' => error_get_last(),
				]
			);
			return false;
		}

		$this->current[] = $path;

		return $path;
	}

	#[\Override]
	public function clean(): void {
		$this->cleanFiles($this->current);
	}

	/**
	 * Remove the specified local temporary files and directories.
	 *
	 * Missing paths are ignored. Failures raised while traversing a directory
	 * are logged and processing continues with the remaining paths. The method
	 * does not report whether each path was removed successfully.
	 *
	 * @param list<string> $files Local filesystem paths
	 * @return void
	 */
	protected function cleanFiles(array $files): void {
		foreach ($files as $file) {
			if (!file_exists($file)) {
				continue;
			}
			
			try {
				Files::rmdirr($file);
			} catch (\UnexpectedValueException $ex) {
				$this->log->warning(
					'Error deleting temporary file/folder: {file} - Reason: {error}',
					[
						'file' => $file,
						'error' => $ex->getMessage(),
					]
				);
			}
		}
	}

	#[\Override]
	public function cleanOld(): void {
		$this->cleanFiles($this->getOldFiles());
	}

	/**
	 * Find old temporary paths generated by this manager.
	 *
	 * The returned paths are not removed by this method. Only direct children
	 * of the configured temporary directory whose names begin with
	 * {@see TMP_PREFIX} and whose modification time is more than one hour old
	 * are considered.
	 *
	 * @return list<string> Local filesystem paths older than one hour
	 */
	protected function getOldFiles(): array {
		$dh = opendir($this->tmpBaseDir);
		if ($dh === false) {
			return [];
		}

		$files = [];
		$cutOfTime = time() - self::TMP_STALE;

		while (($file = readdir($dh)) !== false) {
			if (substr($file, 0, 7) === self::TMP_PREFIX) {
				$path = $this->tmpBaseDir . '/' . $file;
				$mtime = filemtime($path);
				if ($mtime < $cutOfTime) {
					$files[] = $path;
				}
			}
		}

		return $files;
	}

	/**
	 * Candidate directories are checked in configuration and environment
	 * priority order, followed by PHP's system temporary directory. If no
	 * usable directory can be found, a fallback directory is obtained through
	 * {@see tempnam()}.
	 */
	#[\Override]
	public function getTempBaseDir(): string {
		if ($this->tmpBaseDir) {
			return $this->tmpBaseDir;
		}

		$directories = [];
		if ($temp = $this->config->getSystemValue('tempdirectory', null)) {
			$directories[] = $temp;
		}
		if ($temp = $this->iniGetWrapper->get('upload_tmp_dir')) {
			$directories[] = $temp;
		}
		if ($temp = getenv('TMP')) {
			$directories[] = $temp;
		}
		if ($temp = getenv('TEMP')) {
			$directories[] = $temp;
		}
		if ($temp = getenv('TMPDIR')) {
			$directories[] = $temp;
		}
		if ($temp = sys_get_temp_dir()) {
			$directories[] = $temp;
		}

		foreach ($directories as $dir) {
			if ($this->checkTemporaryDirectory($dir)) {
				return $dir;
			}
		}

		$temp = tempnam(__DIR__, '');
		if (file_exists($temp)) {
			unlink($temp);
			return dirname($temp);
		}
		throw new \UnexpectedValueException('Unable to detect system temporary directory');
	}

	/**
	 * Check whether a local directory is writable without throwing on failure.
	 *
	 * Any failure while checking the directory is treated as a negative result
	 * and logged.
	 *
	 * @param string $directory Local filesystem directory path
	 * @return bool True if the directory is writable, false otherwise
	 */
	private function checkTemporaryDirectory(string $directory): bool {
		try {
			if (is_writable($directory)) {
				return true;
			}
		} catch (\Exception $e) {
			// suppress any possible errors caused by is_writable
			// checks missing or invalid path or characters, wrong permissions etc
		}

		$this->log->warning(
			'Temporary directory {dir} is not present or writable',
			['dir' => $directory]
		);

		return false;
	}

	/**
	 * Override the directory used for subsequently created temporary paths.
	 *
	 * The supplied directory is stored as-is and is not validated or created by
	 * this method.
	 *
	 * @todo Considering adding to OCP
	 *
	 * @param string $directory Local filesystem directory path
	 * @return void
	 */
	public function overrideTempBaseDir(string $directory): void {
		$this->tmpBaseDir = $directory;
	}
}
